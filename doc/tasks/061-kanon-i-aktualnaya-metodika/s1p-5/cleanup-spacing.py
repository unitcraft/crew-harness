mapping = dict(line.split('=', 1) for line in PAIRS.strip().splitlines() if line)
for key, value in mapping.items():
    assert re.sub(r'\s', '', key) == re.sub(r'\s', '', value), (key, value)

for name in SUBJECTS:
    p = TASK / name
    old = p.read_text(encoding='utf-8')
    chunks = re.split(r'(`[^`]*`)', old)
    for i in range(0, len(chunks), 2):
        s = chunks[i]
        for key in sorted(mapping, key=len, reverse=True):
            s = s.replace(key, mapping[key])
        s = re.sub(r'\bС (\d) ([пдмкс])(?=[ -])', lambda m: 'С' + m[1] + m[2], s)
        s = re.sub(r'\bС (\d)', r'С\1', s)
        s = re.sub(r'\bВ\s+(\d+)', r'В\1', s)
        s = re.sub(r'В-01\s+а', 'В-01а', s)
        s = re.sub(r'(?<=[.!?])(?=045\b)', ' ', s)
        s = re.sub(r'(?<=045)(?=[A-Za-z])', ' ', s)
        s = re.sub(r'(?<=\d)(?=hunks\b)', ' ', s)
        s = re.sub(r'(?<=[А-Яа-яЁё])(?=`)', ' ', s)
        chunks[i] = s
    new = ''.join(chunks)
    assert re.sub(r'\s', '', old) == re.sub(r'\s', '', new), name
    p.write_text(new, encoding='utf-8', newline='\n')
    print(name, 'whitespace-only: OK')
