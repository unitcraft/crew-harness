#!/bin/sh
# Зачем: журналы GitHub Actions публичного репозитория публичны, и показанное в них не вычистить;
#     значения списка запрещённых имён (секрет) маскируются в журнале до запуска любого шага, который мог бы их
#     напечатать. Один скрипт на workflow стражей и пробный workflow журнала: то, что проверила проба, то и работает.
# Проверяет: ничего не судит; читает переменную окружения с заданным именем и для каждой её строки печатает
#     команду маскирования «::add-mask::<строка>». Пустые строки и строки с решёткой первым знаком пропускаются,
#     конец строки CRLF приводится к LF, обратные косые, процент, звёздочки и кавычки печатаются как есть
#     (printf '%s', не echo: echo и read без -r в dash съедают обратные косые). Строка с ведущими или хвостовыми
#     пробелами маскируется и с ними, и без них.
# Не проверяет: сам журнал (это делает проба AC-31 на служебной ветке) и содержимое значений.
# Правило: ADR-0006 (публичный репозиторий), AGENTS.md п.15; REQ-04 задачи.
#
# Использование: sh scripts/guards/ci-mask.sh <ИМЯ_ПЕРЕМЕННОЙ>
# Пустая или не заданная переменная - ничего не печатает (отсутствие списка краснит страж, не этот скрипт).
set -u

name=${1-}
case "$name" in
  ''|[0-9]*|*[!A-Za-z0-9_]*)
    echo "FAIL: предпосылка: нужно имя переменной окружения (буквы, цифры, подчёркивание)" >&2
    exit 2 ;;
esac

eval "value=\${$name-}"

cr=$(printf '\r')
printf '%s\n' "$value" | while IFS= read -r line; do
  line=${line%"$cr"}
  trimmed=${line#"${line%%[![:space:]]*}"}
  trimmed=${trimmed%"${trimmed##*[![:space:]]}"}
  [ -z "$trimmed" ] && continue
  case "$trimmed" in '#'*) continue ;; esac
  printf '%s\n' "::add-mask::$trimmed"
  if [ "$trimmed" != "$line" ]; then
    printf '%s\n' "::add-mask::$line"
  fi
done
