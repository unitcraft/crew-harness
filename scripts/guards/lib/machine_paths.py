# -*- coding: utf-8 -*-
"""Определение «путь машины»: одно для стража индекса, стража дерева и стража сообщения.

Зачем: репозиторий публичный, а история без силового пуша не чистится; путь вида «диск, папка,
    папка» или домашний каталог с именем пользователя выдаёт машину владельца. Определение одно на
    всех, иначе индекс пропустит то, что дерево потом найдёт (или наоборот).
Проверяет: (а) путь от буквы диска: буква отдельным словом (перед ней нет буквы, цифры или
    обратной косой черты), двоеточие, разделитель, не меньше двух сегментов; (б) домашний каталог
    Linux или macOS с именем пользователя.
Не проверяет: имена проектов и репозиториев (их ловит список из файла вне репозитория,
    names.py); общий корень примеров на диске C с папкой work; корень диска и корни домашних
    каталогов без имени (образцы поиска в правилах); тильду без имени; регулярные выражения
    времени с классом цифр (перед буквой d стоит обратная косая, это не буква диска).
Правило: AGENTS.md п.15, ADR-0006.

Функция find_machine_paths возвращает виды найденного, а не сами значения: значение нигде не печатается.
"""
import sys

sys.dont_write_bytecode = True

import re

_SEG = r"[^\s\\/:*?\"<>|`'()\[\]{}]+"
_DISK = re.compile(r"(?<![A-Za-z0-9\\])([A-Za-z]):[\\/](" + _SEG + r")[\\/](" + _SEG + r")")
_HOME = re.compile(r"(?<![A-Za-z0-9_.~-])/(?:home|Users)/[A-Za-z0-9_][A-Za-z0-9_.-]*")


def find_machine_paths(line):
    """Виды путей машины в строке: список из «disk-path» и «home-path» (без значений)."""
    kinds = []
    for m in _DISK.finditer(line):
        if m.group(1).lower() == "c" and m.group(2).lower() == "work":
            continue  # общий корень примеров
        kinds.append("disk-path")
        break
    if _HOME.search(line):
        kinds.append("home-path")
    return kinds
